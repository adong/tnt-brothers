#!/usr/bin/env node
/* Headless level check: proves every level can be finished, by having the bot (js/bot.js) play it with the real
   engine (js/engine.js), and writes the winning runs to js/demos.js for the title-screen demo.

     node tools/check.js            check all 10 levels (about a minute)
     node tools/check.js 3 7        check levels 3 and 7 only
     node tools/check.js --broken   proves the check can fail: with a 14-tile hole carved in the middle, every level must FAIL
     node tools/check.js --no-write don't touch js/demos.js
     node tools/check.js --walk     never press run: can a little one finish every level at walking speed?
*/
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const ctx = { console, Math, Date, JSON };
ctx.window = ctx;
vm.createContext(ctx);
for (const f of ['js/levels.js', 'js/engine.js', 'js/bot.js']) vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx, { filename: f });
const { engine: E, bot } = ctx.TNT;

const args = process.argv.slice(2);
const broken = args.includes('--broken');
const walk = args.includes('--walk');
const write = !args.includes('--no-write') && !broken && !walk;
const pick = args.filter((a) => /^\d+$/.test(a)).map((a) => +a - 1);
const levels = pick.length ? pick : [...Array(E.levelCount()).keys()];

let warnings = 0;
for (let i = 0; i < E.levelCount(); i++) {
  for (const w of E.prep(i).warn) {
    console.log('WARNING ' + w);
    warnings++;
  }
}

const demosFile = path.join(root, 'js/demos.js');
const demos = {};
try {
  const old = fs.readFileSync(demosFile, 'utf8').match(/window\.TNT_DEMOS = (\{[\s\S]*?\});/);
  if (old) Object.assign(demos, JSON.parse(old[1]));
} catch (e) { /* first run */ }

let fails = 0;
for (const li of levels) {
  const lv = E.prep(li);
  const t0 = Date.now();
  const opts = { beam: 150, maxSeconds: broken ? 60 : 200, walk };
  if (broken) {
    // carve a 14-tile hole into the ground halfway through, and take away anything in it that you could bounce
    // off (a drone over the hole is a real way across: the bot found it)
    opts.mutate = (S) => {
      const x0 = Math.floor(S.W / 2);
      for (let x = x0; x < x0 + 14; x++) for (let y = 0; y < E.H; y++) S.tiles[y * S.W + x] = 0;
      S.ents = S.ents.filter((e) => (e.x0 ?? e.hx ?? e.x) < x0 - 4 || (e.x0 ?? e.hx ?? e.x) > x0 + 18);
    };
  }
  const r = bot.solve(li, opts);
  const secs = ((Date.now() - t0) / 1000).toFixed(1);
  const w = lv.main.W;
  if (r.ok) {
    console.log(`PASS level ${li + 1} ${lv.name.padEnd(18)} ${w} tiles wide, finished in ${r.seconds} s of game time (${r.nodes} tries, ${secs} s)`);
    demos[li + 1] = r.demo;
  } else {
    fails++;
    console.log(`FAIL level ${li + 1} ${lv.name.padEnd(18)} ${w} tiles wide: ${r.reason}, got as far as x = ${r.best} (${secs} s)`);
  }
}

if (write && !fails) {
  const body = JSON.stringify(demos, null, 1);
  fs.writeFileSync(demosFile, `/* Winning runs found by the level bot (tools/check.js), replayed as demos behind the title screen.
   Each letter is 0.1 s of buttons (see js/bot.js). Regenerated by \`node tools/check.js\`; don't edit by hand. */
window.TNT_DEMOS = ${body};
`);
  console.log('wrote js/demos.js');
}
console.log(broken ? (fails ? `OK: the broken level failed as it should (${fails} of ${levels.length})` : 'PROBLEM: the broken level passed') : fails ? `${fails} level(s) FAILED` : `all ${levels.length} level(s) can be finished` + (warnings ? `, ${warnings} warning(s)` : ''));
process.exit(broken ? (fails === levels.length ? 0 : 1) : fails ? 1 : 0);
